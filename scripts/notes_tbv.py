#!/usr/bin/env python3
# TRUST BUT VERIFY: notes here describe the code as it was when written. Read the code (and production) before relying on one.
"""
notes_tbv.py: every note says TRUST BUT VERIFY and points at code by name, never by line number.

Eric, 23 Nov 2026: "point it to the code it's referencing and say before trusting the note, verify ... write into your
wiring- not a rule becuase rules dont work ... on every repo in every project under every claude account ever."

ONE implementation, used by three callers so they can never disagree about where the line goes:
  - Claude Code hook:  ~/.claude/hooks/notes-trust-but-verify.py  (PreToolUse on Write|Edit|MultiEdit, every session)
  - git pre-commit:    ~/.claude/githooks/pre-commit -> `notes_tbv.py precommit` (every commit on this Mac)
  - a repo's CI:       a byte-identical copy at <repo>/scripts/notes_tbv.py -> `notes_tbv.py ci <base-ref>`

What it enforces:
  1. Every code file and every note-type Markdown file carries the TRUST BUT VERIFY line (`has_banner`), placed by
     `insert_banner` (after the file's opening docstring/header comment, so nothing that reads a file's first line breaks).
  2. No NEW pointer by line number ("deps.py:239") in a note: point at the code by name instead ("deps.py::role_allows"). (notes-ok: an example)
     A line that must keep one (a runtime string, a quoted log) carries the marker `notes-ok` on the same line.

Not covered (exempt): vendored/build/generated folders, minified files, `.d.ts`, and any path listed (glob, one per line,
relative to the repo root) in the repo's `.notes-exempt` file, e.g. Markdown the app reads at runtime (prompts, email
bodies, knowledge files). Fails open: any internal error lets the write/commit through and is logged.

Usage:
  notes_tbv.py fix <file>...          add the line where missing (same placement as every caller)
  notes_tbv.py precommit              git pre-commit check (adds the line to fully staged files, blocks new line pointers)
  notes_tbv.py ci <base-ref> [--all]  CI: files this change touches carry the line (--all: every tracked file);
                                      no new line pointers since <base-ref>
  notes_tbv.py apply-all              add the line to every tracked eligible file in this repo (the one-time sweep)
"""
from __future__ import annotations

import ast
import fnmatch
import os
import re
import subprocess
import sys
from pathlib import Path

MARKER = "TRUST BUT VERIFY"
BANNER = "TRUST BUT VERIFY: notes here describe the code as it was when written. Read the code (and production) before relying on one."
MD_BANNER = ("> **TRUST BUT VERIFY:** this note describes code as it was when written. Read the code it names "
             "(and production) before relying on it.")
OK_MARK = "notes-ok"

COMMENT = {
    ".py": "#", ".sh": "#", ".bash": "#", ".zsh": "#", ".rb": "#",
    ".ts": "//", ".tsx": "//", ".js": "//", ".jsx": "//", ".mjs": "//", ".cjs": "//", ".go": "//", ".java": "//",
    ".kt": "//", ".swift": "//", ".rs": "//", ".c": "//", ".h": "//", ".cpp": "//", ".cs": "//",
    ".sql": "--",
}
EXEMPT_DIRS = {
    "node_modules", ".next", "dist", "build", "out", "vendor", ".venv", "venv", "__pycache__", "coverage", ".git",
    "public", "static", ".turbo", "site-packages", "generated", "__generated__", ".pytest_cache", ".mypy_cache",
    "plugins", "cache", ".cache", "fixtures",
}
# Markdown the app may read at runtime or that is not a note (templates, prompts, content shown to people).
MD_RUNTIME_PARTS = ("/knowledge/", "/prompts/", "/prompt/", "/templates/", "/template/", "/.github/", "/skills/",
                    "/content/", "/posts/", "/blog/", "/emails/", "/email/", "/copy/")
MD_RUNTIME_NAMES = ("SYSTEM_PROMPT", "PROMPT", "SKILL.md", "LICENSE", "CODE_OF_CONDUCT")
# Markdown that is always a note, safe for the commit hook to fix by itself.
MD_SAFE_NAMES = {"README.md", "CLAUDE.md", "AGENTS.md", "PROGRESS.md", "PLAN.md", "ASK.md", "DIAGNOSIS.md", "GO-LIVE.md"}
MD_SAFE_PARTS = ("/docs/", "/specs/", "/plans/", "/reviews/", "/memory/", "/tasks/", "/rules/")
GENERATED_HINTS = ("@generated", "do not edit", "auto-generated", "autogenerated", "generated by")

CITATION_RE = re.compile(
    r"(?<![\w/.-])[\w./-]*[A-Za-z_][\w-]*\.(?:py|tsx?|jsx?|mjs|cjs|sh|go|rb|java|kt|swift|rs|sql):\d+(?:-\d+)?(?!\d)")


# ----------------------------------------------------------------------------------------------------------- scope --
def repo_root(path: Path) -> Path | None:
    for parent in [path.parent, *path.parent.parents]:
        if (parent / ".git").exists():
            return parent
    return None


def _exempt_globs(root: Path | None) -> list[str]:
    if root is None:
        return []
    f = root / ".notes-exempt"
    try:
        return [ln.strip() for ln in f.read_text(encoding="utf-8").splitlines() if ln.strip() and not ln.startswith("#")]
    except OSError:
        return []


def kind_of(path: str | Path, root: Path | None = None) -> str | None:
    """'code', 'md-safe', 'md' or None (not covered)."""
    p = Path(path)
    name = p.name
    if root is None:
        root = repo_root(p.resolve()) if p.is_absolute() else None
    try:
        rel = str(p.resolve().relative_to(root.resolve())) if (root and p.is_absolute()) else str(p)
    except ValueError:
        rel = str(p)
    if any(part in EXEMPT_DIRS for part in Path(rel).parts[:-1]):
        return None
    if name.endswith((".min.js", ".d.ts")):
        return None
    for g in _exempt_globs(root):
        if fnmatch.fnmatch(rel, g) or fnmatch.fnmatch(name, g):
            return None
    ext = p.suffix.lower()
    if ext in COMMENT:
        return "code"
    if ext == ".md":
        slashed = "/" + rel.replace(os.sep, "/")
        if any(part in slashed for part in MD_RUNTIME_PARTS) or any(n in name for n in MD_RUNTIME_NAMES):
            return None
        if name in MD_SAFE_NAMES or any(part in slashed for part in MD_SAFE_PARTS):
            return "md-safe"
        return "md"
    return None


#: Note folders outside any git repo that are still notes (the TBHC Board's specs, plans and reviews).
NOTE_ROOTS = (str(Path.home() / "tbhc-board"),)


def in_scope(path: Path) -> bool:
    """A file Claude writes is checked when it sits in a git repo (any project), a Claude memory folder or a NOTE_ROOTS folder."""
    s = str(path)
    if "/.claude/projects/" in s and "/memory/" in s:
        return True
    if any(s.startswith(r + os.sep) for r in NOTE_ROOTS):
        return True
    return repo_root(path) is not None


def looks_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:6]).lower()
    return any(h in head for h in GENERATED_HINTS)


# ------------------------------------------------------------------------------------------------------------ files --
def read_text(path: Path) -> str:
    """Read keeping line endings as they are (CRLF stays CRLF), so adding the line never rewrites the whole file."""
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def write_text(path: Path, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


# ---------------------------------------------------------------------------------------------------------- banner --
#: The line itself, as a comment / quote at the start of a line. Merely mentioning the words does not count.
BANNER_LINE_RE = re.compile(r"^\s*(?:#|//|--|>)\s*(?:\*\*)?TRUST BUT VERIFY:", re.M)


def has_banner(text: str) -> bool:
    return BANNER_LINE_RE.search(text) is not None


def _py_insert_at(lines: list[str], text: str) -> int:
    i = 0
    while i < len(lines) and i < 2 and (lines[i].startswith("#!") or re.match(r"#.*coding[:=]", lines[i])):
        i += 1
    try:
        tree = ast.parse(text)
        if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], "value", None), ast.Constant) \
                and isinstance(tree.body[0].value.value, str):
            return tree.body[0].end_lineno or i
    except SyntaxError:
        pass
    return i


def _js_insert_at(lines: list[str]) -> int:
    i = 0
    if lines and lines[0].startswith("#!"):
        i = 1
    while i < len(lines) and re.match(r"""\s*['"]use (client|server|strict)['"];?\s*$""", lines[i]):
        i += 1
    while i < len(lines):  # step past every leading comment (block or line), e.g. a header or `// @ts-nocheck`
        if lines[i].lstrip().startswith("/*"):
            j = i
            while j < len(lines) and "*/" not in lines[j]:
                j += 1
            i = j + 1
        elif lines[i].lstrip().startswith("//"):
            i += 1
        else:
            break
    return min(i, len(lines))


def insert_banner(text: str, path: str | Path) -> str:
    """Return text with the banner added in the standard place (unchanged if it already has one)."""
    if has_banner(text):
        return text
    ext = Path(path).suffix.lower()
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.split(nl)
    if ext == ".md":
        i = 0
        if lines and lines[0].strip() == "---":
            for j in range(1, len(lines)):
                if lines[j].strip() == "---":
                    i = j + 1
                    break
        elif lines and lines[0].startswith("# "):
            i = 1
        new = [MD_BANNER, ""] if i == 0 else ["", MD_BANNER]
        if i > 0 and i < len(lines) and lines[i].strip() != "":
            new.append("")
        return nl.join(lines[:i] + new + lines[i:])
    prefix = COMMENT.get(ext)
    if prefix is None:
        return text
    if ext == ".py":
        i = _py_insert_at(lines, text)
    elif prefix == "//":
        i = _js_insert_at(lines)
    else:
        i = 1 if lines and lines[0].startswith("#!") else 0
    return nl.join(lines[:i] + [f"{prefix} {BANNER}"] + lines[i:])


# ------------------------------------------------------------------------------------------------------- citations --
def citations(text: str, path: str | Path) -> list[tuple[int, str]]:
    """(line number, line) for each pointer-by-line-number in text, skipping `notes-ok` lines and Markdown code fences."""
    out, fenced = [], False
    is_md = Path(path).suffix.lower() == ".md"
    for n, line in enumerate(text.splitlines(), 1):
        if is_md and line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if fenced or OK_MARK in line:
            continue
        if CITATION_RE.search(line):
            out.append((n, line))
    return out


FIX_HELP = (
    "Point at the code by NAME, not line number: write `deps.py::role_allows`, not `deps.py:239`. Read that code first and "  # notes-ok: example
    "make sure the note is still true. If the line must keep a file:line (a runtime string, a quoted log or traceback), "
    f"add `{OK_MARK}` on that same line."
)


def banner_help(path: str | Path) -> str:
    ext = Path(path).suffix.lower()
    line = MD_BANNER if ext == ".md" else f"{COMMENT.get(ext, '#')} {BANNER}"
    where = ("right after the title line (or front matter)" if ext == ".md"
             else "right after the file's opening docstring/header comment (or at the top if it has none)")
    return (f"Every note-carrying file must hold this exact line, {where}:\n{line}\n"
            f"(`python3 ~/.claude/bin/notes_tbv.py fix <file>` adds it in the standard place.) If this file is read by the "
            f"app at runtime (a prompt, template, email body or page content), list its path in the repo's .notes-exempt "
            f"instead.")


# ------------------------------------------------------------------------------------------------------------- git --
def _git(*args: str, cwd: str | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def _in_merge_or_rebase(git_dir: Path) -> bool:
    return any((git_dir / n).exists() for n in ("MERGE_HEAD", "CHERRY_PICK_HEAD", "REVERT_HEAD", "rebase-merge", "rebase-apply"))


def _added_lines(diff: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    cur = None
    for line in diff.splitlines():
        if line.startswith("+++ "):
            cur = line[6:] if line.startswith("+++ b/") else None
            continue
        if cur and line.startswith("+") and not line.startswith("+++"):
            out.setdefault(cur, []).append(line[1:])
    return out


def precommit() -> int:
    if os.environ.get("SKIP_NOTES_CHECK") == "1":
        print("notes check: SKIPPED via SKIP_NOTES_CHECK=1")
        return 0
    root = Path(_git("rev-parse", "--show-toplevel").strip())
    git_dir = Path(_git("rev-parse", "--absolute-git-dir").strip())
    if _in_merge_or_rebase(git_dir):
        return 0
    staged = [f for f in _git("diff", "--cached", "--name-only", "--diff-filter=ACMR", cwd=str(root)).splitlines() if f]
    unstaged = set(_git("diff", "--name-only", cwd=str(root)).splitlines())
    fixed, missing = [], []
    for rel in staged:
        k = kind_of(root / rel, root)
        if k is None:
            continue
        try:
            blob = _git("show", f":{rel}", cwd=str(root))
        except subprocess.CalledProcessError:
            continue
        if has_banner(blob) or looks_generated(blob):
            continue
        if k in ("code", "md-safe") and rel not in unstaged:
            path = root / rel
            write_text(path, insert_banner(read_text(path), rel))
            _git("add", "--", rel, cwd=str(root))
            fixed.append(rel)
        else:
            missing.append(rel)
    bad = []
    added = _added_lines(_git("diff", "--cached", "-U0", "--diff-filter=ACMR", cwd=str(root)))
    for rel, lines in added.items():
        if kind_of(root / rel, root) != "code":
            continue
        for ln in lines:
            if OK_MARK not in ln and CITATION_RE.search(ln):
                bad.append(f"  {rel}: {ln.strip()[:160]}")
    if fixed:
        print(f"notes check: added the TRUST BUT VERIFY line to {len(fixed)} staged file(s): " + ", ".join(fixed[:8])
              + (" ..." if len(fixed) > 8 else ""))
    if missing or bad:
        print("notes check: COMMIT REFUSED", file=sys.stderr)
        for rel in missing:
            print(f"  missing the TRUST BUT VERIFY line: {rel}", file=sys.stderr)
        if missing:
            print("  fix: python3 ~/.claude/bin/notes_tbv.py fix <file>  then git add it. A Markdown file the app reads at "
                  "runtime (prompt, template, page content) goes in the repo's .notes-exempt instead.", file=sys.stderr)
        if bad:
            print("  new pointer(s) by line number:", file=sys.stderr)
            print("\n".join(bad[:20]), file=sys.stderr)
            print("  " + FIX_HELP, file=sys.stderr)
        print("  (override, and say so out loud: SKIP_NOTES_CHECK=1 git commit ...)", file=sys.stderr)
        return 1
    return 0


def _tracked_eligible(root: Path) -> list[str]:
    out = []
    for rel in _git("ls-files", cwd=str(root)).splitlines():
        if kind_of(root / rel, root) in ("code", "md-safe", "md"):
            out.append(rel)
    return out


def apply_all() -> int:
    root = Path(_git("rev-parse", "--show-toplevel").strip())
    n = 0
    for rel in _tracked_eligible(root):
        path = root / rel
        try:
            text = read_text(path)
        except (OSError, UnicodeDecodeError):
            continue
        if has_banner(text) or looks_generated(text):
            continue
        write_text(path, insert_banner(text, rel))
        n += 1
    print(f"apply-all: added the line to {n} file(s)")
    return 0


def ci(base: str, check_all: bool = False) -> int:
    """A pull request checks only the files it touches (so a file that reached main some other way never turns every
    open PR red); a scheduled or manual run passes --all and checks every tracked file."""
    root = Path(_git("rev-parse", "--show-toplevel").strip())
    missing = []
    if check_all:
        files = _tracked_eligible(root)
    else:
        try:
            changed = _git("diff", "--name-only", "--diff-filter=ACMR", f"{base}...HEAD", cwd=str(root)).splitlines()
        except subprocess.CalledProcessError:
            changed = []
        files = [f for f in changed if f and kind_of(root / f, root) in ("code", "md-safe", "md")]
    for rel in files:
        try:
            text = read_text(root / rel)
        except (OSError, UnicodeDecodeError):
            continue
        if not has_banner(text) and not looks_generated(text):
            missing.append(rel)
    bad = []
    try:
        diff = _git("diff", "-U0", "--diff-filter=ACMR", f"{base}...HEAD", cwd=str(root))
    except subprocess.CalledProcessError:
        diff = ""
    for rel, lines in _added_lines(diff).items():
        if kind_of(root / rel, root) != "code":
            continue
        bad += [f"  {rel}: {ln.strip()[:160]}" for ln in lines if OK_MARK not in ln and CITATION_RE.search(ln)]
    if missing:
        print(f"{len(missing)} file(s) lack the TRUST BUT VERIFY line (run: python3 scripts/notes_tbv.py fix <file>):")
        print("\n".join("  " + m for m in missing[:50]))
    if bad:
        print("New pointer(s) by line number in this change:")
        print("\n".join(bad[:50]))
        print(FIX_HELP)
    return 1 if (missing or bad) else 0


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    cmd, rest = argv[0], argv[1:]
    if cmd == "fix":
        for f in rest:
            p = Path(f)
            if kind_of(p.resolve()) is None:
                print(f"skip (not covered): {f}")
                continue
            write_text(p, insert_banner(read_text(p), f))
            print(f"ok: {f}")
        return 0
    if cmd == "precommit":
        try:
            return precommit()
        except Exception as exc:  # fail open: a broken check must never block work
            print(f"notes check: skipped after an internal error ({type(exc).__name__}: {exc})", file=sys.stderr)
            return 0
    if cmd == "apply-all":
        return apply_all()
    if cmd == "ci":
        args = [a for a in rest if a != "--all"]
        return ci(args[0] if args else "origin/main", check_all="--all" in rest)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
